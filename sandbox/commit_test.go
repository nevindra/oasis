func TestConcurrentToolCallsDoNotRaceEachOtherIntoAConflict(t *testing.T) {
	mount := newTxFakeMount()
	sb := newCommitSandbox(func(s *recordingSandbox) {
		writeGuestFile(s, "/workspace/a.md", "written once")
		writeGuestFile(s, "/workspace/b.md", "written once")
	})
	tools := Tools(sb, WithMounts(workspaceSpec(mount), NewManifest()), WithToolCallCommits(NewFullScanDetector()))

	results := make(chan oasis.ToolResult, 2)
	go func() { results <- runToolAsync(tools, "shell", `{"command":"build"}`) }()
	go func() { results <- runToolAsync(tools, "execute_code", `{"code":"build()"}`) }()
	for range 2 {
		res := <-results
		if strings.Contains(decodeContent(t, res), "workspace commit failed") {
			t.Errorf("parallel tool calls conflicted with each other: %q", decodeContent(t, res))
		}
	}

	for _, key := range []string{"a.md", "b.md"} {
		if got := mount.entries[key].version; got != "v1" {
			t.Errorf("%s version = %q, want v1 — two sweeps committed the same bytes twice", key, got)
		}
	}
}

// runToolAsync is runTool without the *testing.T, for use off the test
// goroutine.
func runToolAsync(tools []oasis.AnyTool, name, args string) oasis.ToolResult {
	tool := findToolByName(tools, name)
	res, err := tool.ExecuteRaw(context.Background(), json.RawMessage(args))
	if err != nil {
		return oasis.ToolResult{Error: err.Error()}
	}
	return res
}

// ── a rejected commit ──

func TestRejectedCommitNotesTheResultAndRetriesNextCall(t *testing.T) {
	mount := newTxFakeMount()
	mount.seed("doc.md", "theirs", "v2") // a second writer moved it since prefetch

	manifest := NewManifest()
	manifest.Record("/workspace", "doc.md", MountEntry{Key: "doc.md", Size: int64(len("prefetched")), Version: "v1"})

	sb := newCommitSandbox(func(s *recordingSandbox) {
		writeGuestFile(s, "/workspace/doc.md", "mine")
	})
	tools := Tools(sb, WithMounts(workspaceSpec(mount), manifest), WithToolCallCommits(NewFullScanDetector()))

	res := runTool(t, tools, "shell", `{"command":"edit doc.md"}`)

	if res.Error != "" {
		t.Errorf("a failed commit turned a successful shell call into an error: %q", res.Error)
	}
	if !strings.Contains(decodeContent(t, res), "ran edit doc.md") {
		t.Errorf("the tool's own output was lost: %q", decodeContent(t, res))
	}
	if !strings.Contains(decodeContent(t, res), "workspace commit failed") {
		t.Errorf("the failure was not surfaced at all: %q", decodeContent(t, res))
	}
	if got := string(mount.entries["doc.md"].data); got != "theirs" {
		t.Errorf("backend doc.md = %q, want the other writer's content untouched", got)
	}

	// The rejection taught the framework the version it was missing, and the
	// framework kept it. Asserting v1 again would be asserting something it now
	// knows to be false, and the backend would reject it for the same reason
	// forever. See adoptRejectedVersions.
	if ver, _ := manifest.Version("/workspace", "doc.md"); ver != "v2" {
		t.Errorf("manifest version = %q after a rejected commit, want v2 — the version the rejection reported", ver)
	}

	// PRD success criterion 5, end to end: the second writer is rejected, and
	// then retries **successfully**, with no help from the test. Before
	// adoptRejectedVersions this test had to hand the manifest the new version
	// itself, which is precisely what made the criterion unmet — the loop could
	// not close without something outside the framework closing it.
	//
	// The change is still pending, too: a rejected commit is not recorded as
	// progress, so the same local file is committed again rather than written
	// off as already published.
	runTool(t, tools, "shell", `{"command":"try again"}`)
	if got := string(mount.entries["doc.md"].data); got != "mine" {
		t.Fatalf("backend doc.md = %q after the retry, want the local content — the retry must succeed on its own", got)
	}
	if len(mount.commits) != 2 {
		t.Errorf("backend saw %d commit attempts, want 2", len(mount.commits))
	}
}

