// commitSandbox is a recordingSandbox that can run a command. shell,
// execute_code and mcp_call apply a canned mutation of the guest filesystem —
// which is all "a CLI toolchain wrote a file" means to this package — and the
// glob/download counters record what the change detector cost.
type commitSandbox struct {
	*recordingSandbox
	run       func(s *recordingSandbox)
	globs     atomic.Int64
	downloads atomic.Int64
}

func newCommitSandbox(run func(s *recordingSandbox)) *commitSandbox {
	return &commitSandbox{recordingSandbox: newRecordingSandbox(), run: run}
}

func (s *commitSandbox) Shell(ctx context.Context, req ShellRequest) (ShellResult, error) {
	if s.run != nil {
		s.run(s.recordingSandbox)
	}
	return ShellResult{Output: "ran " + req.Command}, nil
}

func (s *commitSandbox) ExecCode(ctx context.Context, req CodeRequest) (CodeResult, error) {
	if s.run != nil {
		s.run(s.recordingSandbox)
	}
	return CodeResult{Status: "ok", Stdout: "done"}, nil
}

func (s *commitSandbox) MCPCall(ctx context.Context, req MCPRequest) (MCPResult, error) {
	if s.run != nil {
		s.run(s.recordingSandbox)
	}
	return MCPResult{Content: "built"}, nil
}

func (s *commitSandbox) GlobFiles(ctx context.Context, req GlobRequest) (GlobResult, error) {
	s.globs.Add(1)
	return s.recordingSandbox.GlobFiles(ctx, req)
}

func (s *commitSandbox) DownloadFile(ctx context.Context, path string) (io.ReadCloser, error) {
	s.downloads.Add(1)
	return s.recordingSandbox.DownloadFile(ctx, path)
}

// writeGuestFile is what a command does from this package's point of view.
func writeGuestFile(s *recordingSandbox, path, content string) {
	if err := s.WriteFile(context.Background(), WriteFileRequest{Path: path, Content: content}); err != nil {
		panic(err)
	}
}

func runTool(t *testing.T, tools []oasis.AnyTool, name, args string) oasis.ToolResult {
	t.Helper()
	tool := findToolByName(tools, name)
	if tool == nil {
		t.Fatalf("%s tool not registered", name)
	}
	res, err := tool.ExecuteRaw(context.Background(), json.RawMessage(args))
	if err != nil {
		t.Fatalf("%s returned a transport error: %v", name, err)
	}
	return res
}

func workspaceSpec(backend FilesystemMount, exclude ...string) []MountSpec {
	return []MountSpec{{
		Path:            "/workspace",
		Backend:         backend,
		Mode:            MountReadWrite,
		PrefetchOnStart: true,
		FlushOnClose:    true,
		Exclude:         exclude,
	}}
}

// ── the point of the ticket ──

func TestShellWriteReachesBackendBeforeTheNextToolCall(t *testing.T) {
	mount := newTxFakeMount()
	sb := newCommitSandbox(func(s *recordingSandbox) {
		writeGuestFile(s, "/workspace/report.md", "# generated by typst")
	})
	manifest := NewManifest()
	tools := Tools(sb, WithMounts(workspaceSpec(mount), manifest), WithToolCallCommits(NewFullScanDetector()))

	res := runTool(t, tools, "shell", `{"command":"typst compile report.typ"}`)
	if res.Error != "" {
		t.Fatalf("shell reported an error: %q", res.Error)
	}
	if got := decodeContent(t, res); got != "ran typst compile report.typ" {
		t.Errorf("tool result = %q; the commit must not change what the model sees on success", got)
	}

	// The assertion the PRD makes: durable before the next tool call, not at
	// end of turn. No FlushMounts anywhere in this test.
	if got := string(mount.entries["report.md"].data); got != "# generated by typst" {
		t.Fatalf("backend report.md = %q, want the shell-written content", got)
	}
	if len(mount.commits) != 1 {
		t.Fatalf("backend saw %d commits, want 1", len(mount.commits))
	}
	if got := mount.commits[0][0].Expect; got != ExpectAbsent {
		t.Errorf("precondition = %v, want ExpectAbsent for a file the framework knows was not in the prefetched backend", got)
	}
	if got := mount.commits[0][0].MimeType; got == "" {
		t.Error("the change carried no MimeType; the backend has nothing to serve the file as")
	}
	if ver, ok := manifest.Version("/workspace", "report.md"); !ok || ver == "" {
		t.Error("manifest did not record the version the commit returned; the next commit would assert a stale precondition")
	}
}

