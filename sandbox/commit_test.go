func TestToolCallCommitsAreOffByDefault(t *testing.T) {
	mount := newTxFakeMount()
	sb := newCommitSandbox(func(s *recordingSandbox) {
		writeGuestFile(s, "/workspace/report.md", "written by shell")
	})
	tools := Tools(sb, WithMounts(workspaceSpec(mount), NewManifest()))

	res := runTool(t, tools, "shell", `{"command":"typst compile report.typ"}`)

	// Same result, and not one extra call into the guest or the backend.
	bare := runTool(t, Tools(newCommitSandbox(nil)), "shell", `{"command":"typst compile report.typ"}`)
	if decodeContent(t, res) != decodeContent(t, bare) || res.Error != bare.Error {
		t.Errorf("result with mounts = %+v, without = %+v; the option being unset must change nothing", res, bare)
	}
	if len(mount.commits) != 0 || mount.stages != 0 {
		t.Errorf("backend saw %d commits and %d stages with the option unset, want 0 and 0", len(mount.commits), mount.stages)
	}
	if len(mount.entries) != 0 {
		t.Errorf("backend holds %d entries; without the option a shell write waits for the close-time flush", len(mount.entries))
	}
	if g, d := sb.globs.Load(), sb.downloads.Load(); g != 0 || d != 0 {
		t.Errorf("guest saw %d globs and %d downloads with the option unset, want 0 and 0 — detection must not run at all", g, d)
	}
}

